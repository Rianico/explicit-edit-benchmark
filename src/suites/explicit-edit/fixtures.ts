import { required } from "../../required.ts";
import { createHash } from "node:crypto";

import { mechanicalWorkspaceRules } from "../mechanical-workspace-rules.ts";

import { languageFixtures } from "./language-fixtures.ts";

/** A byte-preserving edit task. Expected files stay in the parent evaluator. */
export interface ExplicitEditTask {
  readonly id: string;
  readonly category: string;
  readonly scale: number;
  readonly scaleUnit: string;
  readonly language: string;
  readonly variant: "plain" | "unicode";
  readonly prompt: string;
  readonly input: Readonly<Record<string, string>>;
  readonly expected: Readonly<Record<string, string>>;
  readonly fixtureSha256: string;
}

type Draft = Omit<ExplicitEditTask, "fixtureSha256">;

/** Generate the fixed smoke matrix, including a Unicode twin for every task. */
export function explicitEditTasks(): readonly ExplicitEditTask[] {
  const tasks: ExplicitEditTask[] = [];
  for (const variant of ["plain", "unicode"] as const) {
    const unicode = variant === "unicode";
    const legacy = unicode ? "legacy\u200bCheckout" : "legacyCheckout";
    const stable = unicode ? "stable\u200bCheckout" : "stableCheckout";
    const label = (n: number) =>
      `${unicode ? "serializes checkout\u2011payload\u00a0" : "serializes checkout-payload "}${String(n).padStart(4, "0")}`;
    const header =
      'import { test, expect } from "vitest";\n\nfunction serializeSettings(settings: Record<string, unknown>): string {\n  return JSON.stringify(settings);\n}\n\n';
    const guard = unicode
      ? "// Preserve: A\u00a0B | A\u202fB | A\u200bB | A\u2060B | dash-\u2010\u2011\u2013\u2014\u2212 | caf\u00e9 | cafe\u0301\n"
      : "// Keep this comment unchanged.\n";
    const testBlock = (n: number, value = legacy) =>
      [
        `test(${JSON.stringify(label(n))}, () => {`,
        "  const input = {",
        `    feature: ${JSON.stringify(value)},`,
        `    requestId: ${JSON.stringify(`request-${n}`)},`,
        `    retryCount: ${n % 4},`,
        '    headers: { accept: "application/json" },',
        "  };",
        "  const encoded = serializeSettings(input);",
        "  expect(JSON.parse(encoded)).toEqual(input);",
        "});\n",
      ].join("\n");
    const add = (
      category: string,
      scale: number,
      input: Record<string, string>,
      expected: Record<string, string>,
      instruction: string,
      suffix = "",
    ) => {
      const draft: Draft = {
        id: `${category}-${scale}${suffix}-${variant}`,
        category,
        scale,
        scaleUnit: scaleUnit(category),
        language: category.startsWith("language-")
          ? suffix.startsWith("-markdown")
            ? "markdown"
            : suffix.slice(1)
          : ["literal", "unicode-fix"].includes(category)
            ? "text"
            : "typescript",
        variant,
        input: { ...input, "untouched.txt": `Do not edit this file.\n${guard}` },
        expected: { ...expected, "untouched.txt": `Do not edit this file.\n${guard}` },
        prompt: [
          "Perform only the following mechanical file edits. The required change is fully specified; no bug investigation is needed.",

          mechanicalWorkspaceRules,
          "Quoted text in this request uses JSON string notation: decode escapes to the actual characters. Treat it as literal text, not a regular expression.",
          instruction,
          "Leave all text outside the requested edits unchanged. Do not create extra files. Choose any available tools, including Bash. Complete the edits and then finish.",
        ].join("\n\n"),
      };
      tasks.push({
        ...draft,
        fixtureSha256: createHash("sha256").update(JSON.stringify(draft)).digest("hex"),
      });
    };

    for (const fixture of languageFixtures(unicode)) {
      const [oldValue, newValue] = fixture.values ?? [legacy, stable];
      const suffix = `-${fixture.language}${fixture.writingSystem ? `-${fixture.writingSystem}` : ""}`;
      const entries = Array.from({ length: 10 }, (_, n) => fixture.entry(n + 1, oldValue));
      const input = { [fixture.file]: fixture.render(entries) };
      add(
        "language-replace",
        10,
        input,
        { [fixture.file]: fixture.render(entries.map((_, n) => fixture.entry(n + 1, newValue))) },
        `In ${fixture.file}, replace all 10 occurrences of ${q(oldValue)} with ${q(newValue)}.`,
        suffix,
      );
      add(
        "language-select",
        10,
        input,
        {
          [fixture.file]: fixture.render(
            entries.map((entry, n) => (n === 4 ? fixture.entry(5, newValue) : entry)),
          ),
        },
        `In ${fixture.file}, replace the exact entry ${q(required(entries[4]))} with ${q(fixture.entry(5, newValue))}. Leave the nine other entries unchanged.`,
        suffix,
      );
      const inserted = fixture.entry(11, newValue);
      const payload = fixture.language === "json" ? inserted + ",\n" : inserted;
      add(
        "language-insert",
        1,
        input,
        { [fixture.file]: fixture.render([...entries.slice(0, 4), inserted, ...entries.slice(4)]) },
        `In ${fixture.file}, insert exactly ${q(payload)} immediately before the exact entry ${q(required(entries[4]))}. Leave all existing text unchanged.`,
        suffix,
      );
    }

    // Same single edit with increasingly large unrelated context.
    for (const lines of [10, 100, 1000]) {
      const filler = Array.from(
        { length: lines },
        (_, n) =>
          `export const route${n} = { path: "/api/items/${n}", method: "GET", timeoutMs: ${1000 + n} } as const;\n`,
      );
      const middle = Math.floor(lines / 2);
      const before = guard + filler.slice(0, middle).join("");
      const after = filler.slice(middle).join("");
      const setting = (feature: string) =>
        `export const checkoutSettings = { feature: ${JSON.stringify(feature)}, retries: 3, enabled: true };\n`;
      add(
        "unique",
        lines,
        { "settings.ts": before + setting(legacy) + after },
        { "settings.ts": before + setting(stable) + after },
        `In settings.ts, replace its one occurrence of ${q(legacy)} with ${q(stable)}.`,
      );
    }

    for (const count of [1, 10, 100, 1000]) {
      const blocks = Array.from({ length: count }, (_, n) => n + 1);
      add(
        "replace-all",
        count,
        { "cases.test.ts": header + guard + blocks.map((n) => testBlock(n)).join("\n") },
        { "cases.test.ts": header + guard + blocks.map((n) => testBlock(n, stable)).join("\n") },
        `In cases.test.ts, replace all ${count} occurrences of ${q(legacy)} with ${q(stable)}.`,
      );
    }

    for (const files of [1, 10, 100]) {
      const input: Record<string, string> = {};
      const expected: Record<string, string> = {};
      const perFile = 1000 / files;
      for (let file = 1; file <= files; file += 1) {
        const name = `cases/part-${String(file).padStart(3, "0")}.test.ts`;
        const blocks = Array.from({ length: perFile }, (_, n) => n + 1);
        input[name] = header + guard + blocks.map((n) => testBlock(n)).join("\n");
        expected[name] = header + guard + blocks.map((n) => testBlock(n, stable)).join("\n");
      }
      input["outside.test.ts"] = header + testBlock(0);
      expected["outside.test.ts"] = input["outside.test.ts"];
      add(
        "multi-file",
        files,
        input,
        expected,
        `In every .test.ts file directly inside cases/ (${files} files, 1000 total occurrences), replace every ${q(legacy)} with ${q(stable)}. Do not change outside.test.ts or any other file.`,
      );
    }

    for (const count of [1, 10, 100, 1000]) {
      const selected = Math.ceil(count / 2);
      const blocks = Array.from({ length: count }, (_, n) => n + 1);
      add(
        "select-one",
        count,
        { "cases.test.ts": header + guard + blocks.map((n) => testBlock(n)).join("\n") },
        {
          "cases.test.ts":
            header +
            guard +
            blocks.map((n) => testBlock(n, n === selected ? stable : legacy)).join("\n"),
        },
        `Only inside the test whose exact title is ${q(label(selected))} in cases.test.ts, replace ${q(legacy)} with ${q(stable)}. Leave every other test unchanged.`,
      );
    }

    for (const count of [10, 100, 1000]) {
      const selected = new Set([1, Math.ceil(count / 2), count]);
      const blocks = Array.from({ length: count }, (_, n) => n + 1);
      add(
        "select-subset",
        count,
        { "cases.test.ts": header + guard + blocks.map((n) => testBlock(n)).join("\n") },
        {
          "cases.test.ts":
            header +
            guard +
            blocks.map((n) => testBlock(n, selected.has(n) ? stable : legacy)).join("\n"),
        },
        `In cases.test.ts, replace ${q(legacy)} with ${q(stable)} only inside these three tests: ${[...selected].map((n) => q(label(n))).join(", ")}. Preserve all other tests.`,
      );

      const titles = [...selected].map((n) => q(label(n))).join(", ");
      add(
        "delete-subset",
        count,
        { "cases.test.ts": header + guard + blocks.map((n) => testBlock(n)).join("\n") },
        {
          "cases.test.ts":
            header + guard + blocks.map((n) => (selected.has(n) ? "" : testBlock(n))).join("\n"),
        },
        `In cases.test.ts, delete the complete test calls whose exact titles are ${titles}. For each, delete from the start of its test line through its closing }); line. Leave all other text unchanged.`,
      );
      const extraCheck = '  expect(encoded).toContain("feature");\n';
      add(
        "insert-subset",
        count,
        { "cases.test.ts": header + guard + blocks.map((n) => testBlock(n)).join("\n") },
        {
          "cases.test.ts":
            header +
            guard +
            blocks
              .map((n) =>
                selected.has(n)
                  ? testBlock(n).replace("});\n", extraCheck + "});\n")
                  : testBlock(n),
              )
              .join("\n"),
        },
        `In cases.test.ts, insert exactly ${q(extraCheck)} immediately before the closing }); line of each test with these exact titles: ${titles}. Leave all existing text unchanged and do not insert into other tests.`,
      );
    }

    for (const count of [1, 10, 30]) {
      const input: Record<string, string> = {};
      const expected: Record<string, string> = {};
      const instructions: string[] = [];
      for (let n = 1; n <= count; n += 1) {
        const name = `config/entry-${n}.ts`;
        const oldText = `${legacy}-${n}`;
        const newText = `${stable}-${n * 7}`;
        const config = (feature: string) =>
          guard +
          `export const checkoutConfig = {\n  feature: ${JSON.stringify(feature)},\n  endpoint: "/api/checkout/${n}",\n  retries: ${n % 4},\n  headers: { accept: "application/json" },\n} as const;\n`;
        input[name] = config(oldText);
        expected[name] = config(newText);
        instructions.push(`- ${name}: replace ${q(oldText)} with ${q(newText)}.`);
      }
      add("distinct-edits", count, input, expected, instructions.join("\n"));
    }

    const literals = [
      { name: "regex", old: String.raw`/^(\d*)\..*\.log$/`, next: String.raw`/^(\d+)\..*\.log$/` },
      { name: "quotes", old: 'say "old" \\ ${value}', next: 'say "new" \\ ${value}' },
      { name: "crlf", old: "old\r\nline", next: "new\r\nline" },
      { name: "tabs", old: "old\t\tvalue", next: "new\t\tvalue" },
      { name: "no-final-newline", old: "old value", next: "new value" },
    ];
    for (const literal of literals) {
      const marker = unicode ? "\u2060" : "";
      const old = literal.old + marker;
      const next = literal.next + marker;
      const ending = literal.name === "no-final-newline" ? "" : "\n";
      // A raw text fixture makes escapes and line endings actual file bytes.
      add(
        "literal",
        1,
        { "sample.txt": guard + old + ending },
        { "sample.txt": guard + next + ending },
        `In sample.txt replace the exact text ${q(old)} with ${q(next)}.`,
        `-${literal.name}`,
      );
    }

    if (unicode) {
      const mutations = [
        ["nbsp", "A\u00a0B", "A B"],
        ["narrow-space", "A\u202fB", "A B"],
        ["zero-width", "A\u200bB", "AB"],
        ["word-joiner", "A\u2060B", "AB"],
        ["nonbreaking-hyphen", "A\u2011B", "A-B"],
        ["minus", "A\u2212B", "A-B"],
        ["decomposed", "cafe\u0301", "caf\u00e9"],
        ["cyrillic-a", "p\u0430yload", "payload"],
      ] as const;
      for (const [name, old, next] of mutations) {
        const decoys = `lookalikes: A B | A\u00a0B | A\u202fB | A\u200bB | A\u2060B | A-B | A\u2011B | A\u2212B | caf\u00e9 | cafe\u0301 | payload | p\u0430yload\n`;
        add(
          "unicode-fix",
          1,
          { "sample.txt": decoys + `target: ${old}\n` },
          { "sample.txt": decoys + `target: ${next}\n` },
          `Only in the line starting with ${q("target: ")}, replace ${q(old)} with ${q(next)}. Leave the entire lookalikes line unchanged.`,
          `-${name}`,
        );
      }
    }

    for (const lines of [10, 100, 1000]) {
      const start = `// BEGIN ${label(42)}\n`;
      const end = `// END ${label(42)}\n`;
      const tableTest = (rows: number, feature: string, title: string) =>
        [
          `test(${JSON.stringify(title)}, () => {`,
          "  const samples = [",
          ...Array.from(
            { length: rows },
            (_, n) =>
              `    { requestId: "request-${n}", feature: ${JSON.stringify(feature)}, retries: ${n % 4} },`,
          ),
          "  ];",
          "  for (const sample of samples) {",
          "    expect(JSON.parse(serializeSettings(sample))).toEqual(sample);",
          "  }",
          "});\n",
        ].join("\n");
      const body = tableTest(lines, legacy, "round-trips checkout samples");
      const block = start + body + end;
      const prefix = header + guard + testBlock(9001, "accountSettings") + "\n// PREFIX\n";
      const suffix = "// SUFFIX\n" + testBlock(9002, "shippingSettings");
      const replacement = tableTest(1, stable, "round-trips the default checkout sample");
      add(
        "replace-block",
        lines,
        { "blocks.test.ts": prefix + block + suffix },
        { "blocks.test.ts": prefix + start + replacement + end + suffix },
        `In blocks.test.ts, replace all text between the exact marker lines ${q(start.trimEnd())} and ${q(end.trimEnd())} with ${q(replacement)}. Keep both marker lines unchanged.`,
      );
      add(
        "delete-block",
        lines,
        { "blocks.test.ts": prefix + block + suffix },
        { "blocks.test.ts": prefix + suffix },
        `In blocks.test.ts, delete the block starting with marker line ${q(start.trimEnd())} through marker line ${q(end.trimEnd())}, including both marker lines.`,
      );
      add(
        "move-block",
        lines,
        { "blocks.test.ts": prefix + block + "// OTHER\n" + suffix },
        {
          "blocks.test.ts":
            prefix + "// OTHER\n" + suffix.replace("// SUFFIX\n", "// SUFFIX\n" + block),
        },
        `In blocks.test.ts, move the block from marker line ${q(start.trimEnd())} through marker line ${q(end.trimEnd())}, including both marker lines, to immediately after the line ${q("// SUFFIX")}. Keep the text of the moved block unchanged.`,
      );
      const destination = header + guard + "// TARGET\n" + testBlock(9003, "customerSettings");
      add(
        "copy-block",
        lines,
        { "source.test.ts": prefix + block + suffix, "target.test.ts": destination },
        { "source.test.ts": prefix + block + suffix, "target.test.ts": destination + block },
        `Copy the block from marker line ${q(start.trimEnd())} through marker line ${q(end.trimEnd())} in source.test.ts, including both marker lines, to the end of target.test.ts. Leave source.test.ts unchanged and keep the copied text unchanged.`,
      );
      const supplied = testBlock(9004, stable);
      add(
        "insert-block",
        lines,
        { "blocks.test.ts": prefix + block + suffix },
        { "blocks.test.ts": prefix + block + supplied + suffix },
        `In blocks.test.ts, insert exactly ${q(supplied)} immediately after marker line ${q(end.trimEnd())}. Preserve all existing text.`,
      );

      const payload = tableTest(lines, stable, "round-trips migrated checkout samples");
      add(
        "insert-payload",
        lines,
        { "blocks.test.ts": prefix + suffix },
        { "blocks.test.ts": prefix + payload + suffix },
        `In blocks.test.ts, insert exactly ${q(payload)} immediately before the line ${q("// SUFFIX")}. Preserve all existing text.`,
      );
      add(
        "copy-within",
        lines,
        { "blocks.test.ts": prefix + block + suffix },
        { "blocks.test.ts": prefix + block + suffix + block },
        `In blocks.test.ts, copy the block from marker line ${q(start.trimEnd())} through marker line ${q(end.trimEnd())}, including both marker lines, to the end of the same file. Keep the original block unchanged.`,
      );
      add(
        "move-between",
        lines,
        { "source.test.ts": prefix + block + suffix, "target.test.ts": destination },
        { "source.test.ts": prefix + suffix, "target.test.ts": destination + block },
        `Move the block from marker line ${q(start.trimEnd())} through marker line ${q(end.trimEnd())} in source.test.ts, including both marker lines, to the end of target.test.ts. Remove it from source.test.ts and keep the moved text unchanged.`,
      );
    }
  }
  return tasks;
}

function scaleUnit(category: string): string {
  const units: Readonly<Record<string, string>> = {
    unique: "surrounding-routes",
    "replace-all": "occurrences",
    "multi-file": "files",
    "select-one": "similar-tests",
    "select-subset": "similar-tests",
    "delete-subset": "similar-tests",
    "insert-subset": "similar-tests",
    "distinct-edits": "files",
    literal: "replacement",
    "unicode-fix": "replacement",
    "insert-block": "surrounding-table-rows",
    "insert-payload": "inserted-table-rows",
    "replace-block": "source-table-rows",
    "delete-block": "source-table-rows",
    "copy-block": "source-table-rows",
    "copy-within": "source-table-rows",
    "move-block": "source-table-rows",
    "move-between": "source-table-rows",
    "language-replace": "occurrences",
    "language-select": "similar-entries",
    "language-insert": "inserted-entries",
  };
  const unit = units[category];
  if (unit === undefined) throw new Error(`Missing scale unit for ${category}`);
  return unit;
}

/** Render exact text in prompts, making invisible characters unambiguous. */
function q(value: string): string {
  return JSON.stringify(value).replace(
    /[\u007f-\uffff]/gu,
    (character) => `\\u${character.charCodeAt(0).toString(16).padStart(4, "0")}`,
  );
}
